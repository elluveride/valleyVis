// Java for the HuskyLens pickup: the files a team adds once (Export → Vision setup).
// The maths in HuskyCamera is the same as camera.js / vision.js, so the preview and the robot agree.

import { fmtNum } from './expr.js';

const simple = (fq) => String(fq || '').split('.').pop();
const jd = (v) => fmtNum(Number(v) || 0);
const ji = (v) => String(Math.round(Number(v) || 0));
const jstr = (s) => `"${String(s ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** The lines to paste into Constants.java (Settings → Camera). */
export function constantsLines(settings) {
  const c = settings.camera;
  return [
    '    // ?----- HuskyLens (from ValleyVis Settings → Camera) -----',
    `    public static String HUSKY_NAME = ${jstr(c.deviceName)};`,
    '    /** Lens position from the robot centre (in): x forward, y left, height off the tiles. */',
    `    public static double HUSKY_X = ${jd(c.x)};`,
    `    public static double HUSKY_Y = ${jd(c.y)};`,
    `    public static double HUSKY_HEIGHT = ${jd(c.height)};`,
    '    /** Degrees the camera is turned left of straight ahead, and tilted down. */',
    `    public static double HUSKY_YAW_DEG = ${jd(c.yaw)};`,
    `    public static double HUSKY_PITCH_DEG = ${jd(c.pitch)};`,
    '    /** Field of view (deg). Not published for the HuskyLens: check it with HuskyLensCheck. */',
    `    public static double HUSKY_HFOV_DEG = ${jd(c.hfov)};`,
    `    public static double HUSKY_VFOV_DEG = ${jd(c.vfov)};`,
    '    /** Color IDs as learned on the HuskyLens (Color Recognition). */',
    `    public static int HUSKY_POLLEN_ID = ${ji(c.idPollen)};`,
    `    public static int HUSKY_NECTAR_RED_ID = ${ji(c.idNectarRed)};`,
    `    public static int HUSKY_NECTAR_BLUE_ID = ${ji(c.idNectarBlue)};`,
    '    /** Blobs smaller than this many px² (of 320 x 240) are ignored. */',
    `    public static double HUSKY_MIN_AREA = ${jd(c.minArea)};`,
    '    /** Seconds to look along each heading before turning to the next one. */',
    `    public static double HUSKY_LOOK_TIME = ${jd(c.lookTime)};`,
    '    /** Closer than this (in), stop re-aiming: the ball drops out of the bottom of the image. */',
    `    public static double HUSKY_COMMIT_DISTANCE = ${jd(c.commitDistance)};`,
    '    /** Re-plan the approach when the ball\'s estimate moves more than this (in). */',
    `    public static double HUSKY_REAIM_DISTANCE = ${jd(c.reaimDistance)};`,
    '',
  ].join('\n');
}


function header(settings, extra = []) {
  return [`package ${settings.code.visionPackage};`, '', ...extra.sort().map((i) => `import ${i};`), ''];
}

export function huskyCameraJava(settings) {
  const C = simple(settings.code.constantsImport);
  return [
    ...header(settings, ['com.pedropathing.math.Pose', settings.code.constantsImport]),
    '/**',
    ' * Where a HuskyLens blob is on the field. Generated by ValleyVis: the same maths as its preview,',
    ' * so where the preview says the camera can see a ball, the robot can too.',
    ' * <p>',
    ' * Image: 320 x 240 px, (0, 0) at the top left; a block\'s x, y is its centre.',
    ' * Robot frame: inches from the robot centre, x forward, y left.',
    ' */',
    'public final class HuskyCamera {',
    '    public static final int IMAGE_WIDTH = 320;',
    '    public static final int IMAGE_HEIGHT = 240;',
    '',
    '    /** The BIOBUZZ balls (game manual 9.8). */',
    '    public enum Ball {',
    '        POLLEN(2.8),',
    '        NECTAR(3.6);',
    '',
    '        /** Diameter in inches. */',
    '        public final double diameter;',
    '',
    '        Ball(double diameter) {',
    '            this.diameter = diameter;',
    '        }',
    '',
    '        /** The HuskyLens color ID to look for. Nectar is your own alliance\'s color. */',
    '        public int colorId(int alliance) {',
    `            if (this == POLLEN) return ${C}.HUSKY_POLLEN_ID;`,
    `            return alliance == ${settings.code.redAlliance} ? ${C}.HUSKY_NECTAR_RED_ID : ${C}.HUSKY_NECTAR_BLUE_ID;`,
    '        }',
    '    }',
    '',
    '    private HuskyCamera() {}',
    '',
    '    private static double fx() {',
    `        return IMAGE_WIDTH / 2.0 / Math.tan(Math.toRadians(${C}.HUSKY_HFOV_DEG) / 2.0);`,
    '    }',
    '',
    '    private static double fy() {',
    `        return IMAGE_HEIGHT / 2.0 / Math.tan(Math.toRadians(${C}.HUSKY_VFOV_DEG) / 2.0);`,
    '    }',
    '',
    '    /**',
    '     * The ball whose centre is at pixel (px, py), in the robot frame as {x, y}: the camera ray',
    '     * through that pixel, met with the plane at the ball\'s centre height. Null when the ray',
    '     * never comes down that low (the pixel is above the horizon).',
    '     */',
    '    public static double[] pixelToRobot(double px, double py, double diameter) {',
    '        double a = (IMAGE_WIDTH / 2.0 - px) / fx();',
    '        double b = (py - IMAGE_HEIGHT / 2.0) / fy();',
    `        double pitch = Math.toRadians(${C}.HUSKY_PITCH_DEG);`,
    `        double yaw = Math.toRadians(${C}.HUSKY_YAW_DEG);`,
    '        double cx = Math.cos(pitch) - b * Math.sin(pitch);',
    '        double cz = -Math.sin(pitch) - b * Math.cos(pitch);',
    '        double rx = cx * Math.cos(yaw) - a * Math.sin(yaw);',
    '        double ry = cx * Math.sin(yaw) + a * Math.cos(yaw);',
    '        double ballZ = diameter / 2.0;',
    `        if (!(cz < -1e-9) || !(${C}.HUSKY_HEIGHT > ballZ)) return null;`,
    `        double t = (ballZ - ${C}.HUSKY_HEIGHT) / cz;`,
    `        return new double[] {${C}.HUSKY_X + t * rx, ${C}.HUSKY_Y + t * ry};`,
    '    }',
    '',
    '    /** A robot-frame point {x, y} on the field, for a robot at {@code robot}. */',
    '    public static Pose toField(Pose robot, double[] r) {',
    '        double c = Math.cos(robot.heading());',
    '        double s = Math.sin(robot.heading());',
    '        return new Pose(robot.x() + r[0] * c - r[1] * s, robot.y() + r[0] * s + r[1] * c, 0.0);',
    '    }',
    '',
    '    /** True if p is inside the polygon (field coordinates). */',
    '    public static boolean inside(Pose p, Pose[] area) {',
    '        boolean in = false;',
    '        for (int i = 0, j = area.length - 1; i < area.length; j = i++) {',
    '            Pose a = area[i];',
    '            Pose b = area[j];',
    '            if ((a.y() > p.y()) != (b.y() > p.y())',
    '                    && p.x() < (b.x() - a.x()) * (p.y() - a.y()) / (b.y() - a.y()) + a.x()) {',
    '                in = !in;',
    '            }',
    '        }',
    '        return in;',
    '    }',
    '',
    '    /**',
    '     * Headings (radians) to look along when scanning: the current one, then out to one side in',
    '     * steps of 80% of the field of view as far as halfRangeDeg, then the same on the other side.',
    '     * It looks while it turns, so one sweep covers everything.',
    '     *',
    '     * @param firstDir +1 to try the left first, -1 for the right (see {@link #scanDirection})',
    '     */',
    '    public static double[] scanHeadings(double start, double halfRangeDeg, int firstDir) {',
    '        java.util.List<Double> out = new java.util.ArrayList<>();',
    '        out.add(start);',
    '        double half = Math.min(180.0, Math.max(0.0, halfRangeDeg));',
    `        double step = Math.max(5.0, 0.8 * ${C}.HUSKY_HFOV_DEG);`,
    '        int dir = firstDir < 0 ? -1 : 1;',
    '        for (int side : new int[] {dir, -dir}) {',
    '            for (int k = 1; k * step < half - 1.0; k++) out.add(start + side * Math.toRadians(k * step));',
    '            if (half > 1e-9) out.add(start + side * Math.toRadians(half));',
    '        }',
    '        double[] headings = new double[out.size()];',
    '        for (int i = 0; i < headings.length; i++) headings[i] = out.get(i);',
    '        return headings;',
    '    }',
    '',
    '    /** Which way to scan first: toward the middle of the search area (+1 = left), left if it is dead ahead. */',
    '    public static int scanDirection(Pose robot, Pose[] area) {',
    '        if (area == null || area.length < 3) return 1;',
    '        double cx = 0;',
    '        double cy = 0;',
    '        for (Pose p : area) {',
    '            cx += p.x();',
    '            cy += p.y();',
    '        }',
    '        cx /= area.length;',
    '        cy /= area.length;',
    '        double off = Math.atan2(cy - robot.y(), cx - robot.x()) - robot.heading();',
    '        return Math.sin(off) < 0 ? -1 : 1;',
    '    }',
    '}',
    '',
  ].join('\n');
}

export function huskySubsystemJava(settings) {
  const C = simple(settings.code.constantsImport);
  return [
    ...header(settings, [
      'com.pedropathing.math.Pose',
      'com.qualcomm.hardware.dfrobot.HuskyLens',
      'com.qualcomm.robotcore.hardware.HardwareMap',
      'com.vcs.valleylib.ftc.hardware.FtcSubsystem',
      settings.code.constantsImport,
    ]),
    '/**',
    ' * The HuskyLens in Color Recognition mode. Generated by ValleyVis.',
    ' * <p>',
    ' * Each read is an I2C transaction, so it only reads while something has asked it to',
    ' * (VisionPickupCmd turns reading on and off).',
    ' */',
    'public class HuskyLensSubsystem extends FtcSubsystem {',
    '    private static final HuskyLens.Block[] NONE = new HuskyLens.Block[0];',
    '',
    '    private final HuskyLens huskyLens;',
    '    private final boolean connected;',
    '    private HuskyLens.Block[] blocks = NONE;',
    '    private boolean reading = false;',
    '',
    '    public HuskyLensSubsystem(HardwareMap hardwareMap) {',
    '        super(hardwareMap);',
    `        huskyLens = hardwareMap.get(HuskyLens.class, ${C}.HUSKY_NAME);`,
    '        connected = huskyLens.knock();',
    '        huskyLens.selectAlgorithm(HuskyLens.Algorithm.COLOR_RECOGNITION);',
    '    }',
    '',
    '    /** False if the HuskyLens did not answer when the robot started (check the wiring and the I2C port). */',
    '    public boolean isConnected() {',
    '        return connected;',
    '    }',
    '',
    '    public void setReading(boolean on) {',
    '        reading = on;',
    '        if (!on) blocks = NONE;',
    '    }',
    '',
    '    /** What the camera saw on the last read (empty while not reading). */',
    '    public HuskyLens.Block[] blocks() {',
    '        return blocks;',
    '    }',
    '',
    '    @Override',
    '    public void periodic() {',
    '        if (!reading) return;',
    '        HuskyLens.Block[] seen = huskyLens.blocks();',
    '        blocks = seen == null ? NONE : seen;',
    '    }',
    '',
    '    /**',
    '     * The nearest ball of this color on the field, for a robot at {@code robot}: big enough to',
    '     * trust and inside {@code area} (pass null for anywhere). Null if there is none.',
    '     */',
    '    public Pose findBall(int colorId, double diameter, Pose robot, Pose[] area) {',
    '        Pose best = null;',
    '        double bestDistance = Double.POSITIVE_INFINITY;',
    '        for (HuskyLens.Block b : blocks) {',
    '            if (b.id != colorId) continue;',
    `            if ((double) b.width * b.height < ${C}.HUSKY_MIN_AREA) continue;`,
    '            double[] r = HuskyCamera.pixelToRobot(b.x, b.y, diameter);',
    '            if (r == null) continue;',
    '            Pose ball = HuskyCamera.toField(robot, r);',
    '            if (area != null && area.length >= 3 && !HuskyCamera.inside(ball, area)) continue;',
    '            double d = Math.hypot(ball.x() - robot.x(), ball.y() - robot.y());',
    '            if (d < bestDistance) {',
    '                best = ball;',
    '                bestDistance = d;',
    '            }',
    '        }',
    '        return best;',
    '    }',
    '}',
    '',
  ].join('\n');
}

export function visionPickupCmdJava(settings) {
  const C = simple(settings.code.constantsImport);
  return [
    ...header(settings, [
      'com.pedropathing.api.Paths',
      'com.pedropathing.math.Pose',
      'com.pedropathing.paths.Path',
      'com.vcs.valleylib.core.command.Command',
      'com.vcs.valleylib.core.subsystem.Subsystem',
      'com.vcs.valleylib.ftc.pedro.PedroSubsystem',
      settings.code.constantsImport,
      'java.util.Arrays',
      'java.util.HashSet',
      'java.util.Set',
      'java.util.function.BooleanSupplier',
    ]),
    '/**',
    ' * Find a ball with the HuskyLens and drive to it. Generated by ValleyVis (the pickup step).',
    ' * <ol>',
    ' *   <li>Look along the current heading.</li>',
    ' *   <li>If nothing is there, turn and scan: toward the search area first, then the other way',
    ' *       (HuskyCamera.scanHeadings), looking the whole time.</li>',
    ' *   <li>Once a ball is seen, drive at it nose-first and stop with it {@code reach} inches from the',
    ' *       robot centre. Until the last few inches it re-aims if the ball turns out to be elsewhere.</li>',
    ' * </ol>',
    ' * It finishes when the robot gets there, when the ball-in check says yes, or after scanning',
    ' * every heading without seeing anything. Give it a timeout too.',
    ' */',
    'public class VisionPickupCmd implements Command {',
    '    /** Shortest approach worth driving (Pedro cannot follow a zero-length line). */',
    '    public static final double MIN_MOVE = 0.5;',
    '',
    '    private enum Phase { LOOK, TURN, APPROACH, DONE }',
    '',
    '    private final PedroSubsystem drive;',
    '    private final HuskyLensSubsystem husky;',
    '    private final HuskyCamera.Ball ball;',
    '    private final int alliance;',
    '    private final Pose[] area;',
    '    private final double reach;',
    '    private final double maxSpeed;',
    '    private final double scanDeg;',
    '    private final BooleanSupplier ballIn;',
    '',
    '    private Phase phase;',
    '    private Pose origin;',
    '    private double[] headings;',
    '    private int nextHeading;',
    '    private double lookStart;',
    '    private Pose chasing;',
    '    private boolean found;',
    '',
    '    /**',
    '     * @param area     the search area (field poses, in order around it); balls outside are ignored',
    '     * @param reach    stop with the ball this far from the robot centre (in), e.g. ROBOT_LENGTH / 2',
    '     * @param maxSpeed fraction of top speed for the drive to the ball, or PedroSubsystem.NO_SPEED_LIMIT',
    '     * @param scanDeg  how far to turn each way (deg) when nothing is in view',
    '     */',
    '    public VisionPickupCmd(PedroSubsystem drive, HuskyLensSubsystem husky, HuskyCamera.Ball ball, int alliance,',
    '                           Pose[] area, double reach, double maxSpeed, double scanDeg) {',
    '        this(drive, husky, ball, alliance, area, reach, maxSpeed, scanDeg, () -> false);',
    '    }',
    '',
    '    /** @param ballIn true once a ball is in (a sensor); the pickup ends right away when it is. */',
    '    public VisionPickupCmd(PedroSubsystem drive, HuskyLensSubsystem husky, HuskyCamera.Ball ball, int alliance,',
    '                           Pose[] area, double reach, double maxSpeed, double scanDeg, BooleanSupplier ballIn) {',
    '        this.drive = drive;',
    '        this.husky = husky;',
    '        this.ball = ball;',
    '        this.alliance = alliance;',
    '        this.area = area;',
    '        this.reach = reach;',
    '        this.maxSpeed = maxSpeed;',
    '        this.scanDeg = scanDeg;',
    '        this.ballIn = ballIn;',
    '    }',
    '',
    '    @Override',
    '    public Set<Subsystem> getRequirements() {',
    '        return new HashSet<>(Arrays.asList(drive, husky));',
    '    }',
    '',
    '    /** True if a ball was seen (false after a scan that found nothing). */',
    '    public boolean foundBall() {',
    '        return found;',
    '    }',
    '',
    '    /** Seconds; override in a simulation. */',
    '    protected double now() {',
    '        return System.nanoTime() / 1e9;',
    '    }',
    '',
    '    @Override',
    '    public void initialize() {',
    '        husky.setReading(true);',
    '        origin = drive.getPose();',
    '        headings = HuskyCamera.scanHeadings(origin.heading(), scanDeg, HuskyCamera.scanDirection(origin, area));',
    '        nextHeading = 1;',
    '        chasing = null;',
    '        found = false;',
    '        phase = Phase.LOOK;',
    '        lookStart = now();',
    '    }',
    '',
    '    @Override',
    '    public void execute() {',
    '        if (phase == Phase.DONE) return;',
    '        Pose here = drive.getPose();',
    '        if (phase == Phase.APPROACH) {',
    '            if (ballIn.getAsBoolean()) {',
    '                drive.getFollower().hold(here);',
    '                phase = Phase.DONE;',
    '                return;',
    '            }',
    `            if (distance(here, chasing) > ${C}.HUSKY_COMMIT_DISTANCE) {`,
    '                Pose seen = see(here);',
    `                if (seen != null && distance(seen, chasing) > ${C}.HUSKY_REAIM_DISTANCE) {`,
    '                    approach(here, seen);',
    '                    return;',
    '                }',
    '            }',
    '            if (drive.isIdle()) phase = Phase.DONE;',
    '            return;',
    '        }',
    '        Pose seen = see(here);',
    '        if (seen != null) {',
    '            found = true;',
    '            approach(here, seen);',
    '            return;',
    '        }',
    `        if (phase == Phase.LOOK && now() - lookStart >= ${C}.HUSKY_LOOK_TIME) {`,
    '            if (nextHeading >= headings.length) {',
    '                phase = Phase.DONE;',
    '                return;',
    '            }',
    '            // turn on the spot where the pickup started (what DriveSubsystem.turnTo does)',
    '            drive.getFollower().hold(new Pose(origin.x(), origin.y(), headings[nextHeading++]));',
    '            phase = Phase.TURN;',
    '        } else if (phase == Phase.TURN && drive.isIdle()) {',
    '            phase = Phase.LOOK;',
    '            lookStart = now();',
    '        }',
    '    }',
    '',
    '    private Pose see(Pose here) {',
    '        return husky.findBall(ball.colorId(alliance), ball.diameter, here, area);',
    '    }',
    '',
    '    /** Drive from here to {@code reach} short of the ball, facing it. */',
    '    private void approach(Pose here, Pose target) {',
    '        chasing = target;',
    '        double dx = target.x() - here.x();',
    '        double dy = target.y() - here.y();',
    '        double d = Math.hypot(dx, dy);',
    '        if (d - reach < MIN_MOVE) {',
    '            drive.getFollower().hold(here);',
    '            phase = Phase.DONE;',
    '            return;',
    '        }',
    '        double heading = Math.atan2(dy, dx);',
    '        Pose stop = new Pose(target.x() - dx / d * reach, target.y() - dy / d * reach, heading);',
    '        Path path = Paths.line(here, stop);',
    '        // facing the ball the whole way; right next to it that is undefined, so hold the heading',
    '        path = reach >= 1.0 ? path.facingPoint(target) : path.constant(heading);',
    '        drive.getFollower().follow(drive.withSpeedLimit(path, maxSpeed));',
    '        phase = Phase.APPROACH;',
    '    }',
    '',
    '    private static double distance(Pose a, Pose b) {',
    '        return Math.hypot(a.x() - b.x(), a.y() - b.y());',
    '    }',
    '',
    '    @Override',
    '    public boolean isFinished() {',
    '        return phase == Phase.DONE;',
    '    }',
    '',
    '    @Override',
    '    public void end(boolean interrupted) {',
    '        husky.setReading(false);',
    '        if (interrupted) drive.stop();',
    '    }',
    '}',
    '',
  ].join('\n');
}

export function huskyCheckJava(settings) {
  const C = simple(settings.code.constantsImport);
  return [
    ...header(settings, [
      'com.qualcomm.hardware.dfrobot.HuskyLens',
      'com.qualcomm.robotcore.eventloop.opmode.LinearOpMode',
      'com.qualcomm.robotcore.eventloop.opmode.TeleOp',
      settings.code.constantsImport,
    ]),
    '/**',
    ' * Check the camera numbers before trusting a pickup. Generated by ValleyVis.',
    ' * <ol>',
    ' *   <li>Measure the lens: HUSKY_X/Y/HEIGHT from the robot centre, and teach the ball colors.</li>',
    ' *   <li>Put a ball 24 in straight ahead of the robot centre. Dpad up/down changes the tilt until',
    ' *       "robot frame" reads about x 24, y 0.</li>',
    ' *   <li>Move it 12 in to the left (x 24, y 12). Dpad left/right changes the field of view until',
    ' *       y reads 12. Try a far spot (x 48) and a near one to confirm.</li>',
    ' *   <li>Copy the numbers shown into ValleyVis (Settings → Camera) and Constants.java, then tick',
    ' *       "checked" in ValleyVis.</li>',
    ' * </ol>',
    ' */',
    '@TeleOp(name = "HuskyLens Check", group = "Testing")',
    'public class HuskyLensCheck extends LinearOpMode {',
    '    @Override',
    '    public void runOpMode() {',
    `        HuskyLens huskyLens = hardwareMap.get(HuskyLens.class, ${C}.HUSKY_NAME);`,
    '        boolean connected = huskyLens.knock();',
    '        huskyLens.selectAlgorithm(HuskyLens.Algorithm.COLOR_RECOGNITION);',
    '        telemetry.addData("HuskyLens", connected ? "connected" : "NOT answering: check the wiring and the port");',
    '        telemetry.update();',
    '        waitForStart();',
    '        boolean wasUp = false, wasDown = false, wasLeft = false, wasRight = false;',
    '        while (opModeIsActive()) {',
    `            if (gamepad1.dpad_up && !wasUp) ${C}.HUSKY_PITCH_DEG += 0.5;`,
    `            if (gamepad1.dpad_down && !wasDown) ${C}.HUSKY_PITCH_DEG -= 0.5;`,
    '            if (gamepad1.dpad_right && !wasRight) setHorizontalFov(hfov() + 0.5);',
    '            if (gamepad1.dpad_left && !wasLeft) setHorizontalFov(hfov() - 0.5);',
    '            wasUp = gamepad1.dpad_up;',
    '            wasDown = gamepad1.dpad_down;',
    '            wasLeft = gamepad1.dpad_left;',
    '            wasRight = gamepad1.dpad_right;',
    '',
    `            telemetry.addData("tilt down (pitch)", "%.1f deg  (dpad up/down)", ${C}.HUSKY_PITCH_DEG);`,
    `            telemetry.addData("field of view", "%.1f x %.1f deg  (dpad left/right)", ${C}.HUSKY_HFOV_DEG, ${C}.HUSKY_VFOV_DEG);`,
    '            HuskyLens.Block[] blocks = huskyLens.blocks();',
    '            telemetry.addData("blocks", blocks == null ? 0 : blocks.length);',
    '            if (blocks != null) {',
    '                for (HuskyLens.Block b : blocks) {',
    `                    HuskyCamera.Ball ball = b.id == ${C}.HUSKY_POLLEN_ID ? HuskyCamera.Ball.POLLEN : HuskyCamera.Ball.NECTAR;`,
    '                    double[] r = HuskyCamera.pixelToRobot(b.x, b.y, ball.diameter);',
    `                    boolean small = (double) b.width * b.height < ${C}.HUSKY_MIN_AREA;`,
    '                    telemetry.addLine(String.format("id %d (%s)  pixel (%d, %d)  %dx%d%s", b.id, ball, b.x, b.y, b.width, b.height, small ? "  too small, ignored" : ""));',
    '                    telemetry.addLine(r == null ? "    above the horizon" : String.format("    robot frame: x %.1f  y %.1f in", r[0], r[1]));',
    '                }',
    '            }',
    '            telemetry.update();',
    '        }',
    '    }',
    '',
    '    private static double hfov() {',
    `        return ${C}.HUSKY_HFOV_DEG;`,
    '    }',
    '',
    '    /** Square pixels: the 320 x 240 image keeps a 4:3 shape, so the vertical view follows. */',
    '    private static void setHorizontalFov(double deg) {',
    `        ${C}.HUSKY_HFOV_DEG = Math.max(10.0, Math.min(120.0, deg));`,
    `        double half = Math.toRadians(${C}.HUSKY_HFOV_DEG) / 2.0;`,
    `        ${C}.HUSKY_VFOV_DEG = Math.toDegrees(2.0 * Math.atan(Math.tan(half) * 240.0 / 320.0));`,
    '    }',
    '}',
    '',
  ].join('\n');
}

